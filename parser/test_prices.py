#!/usr/bin/env python3
"""
Проверка разбора цены на живых формулировках из каналов Пхангана.

Каждый кейс здесь — реальный текст (или его сокращение), на котором парсер однажды
ошибся. Ошибка в цене дороже прочих: она попадает в фильтр, в сравнение с медианой
района и в «−24% к рынку», то есть искажает главное обещание витрины.

    python3 parser/test_prices.py
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from parse_lite import _parse_price  # noqa: E402

# (текст, ожидаемая цена, ожидаемый период, чем кейс важен)
CASES = [
    ("Сутки - 1000бат (от 3х дней)\nНеделя - 7000бат\nМесяц - 25 000 бат",
     25000.0, "month", "прайс-лист: берём месяц, а не первую строку"),
    ("Цена за месяц (март) — 80 000 бат. Цена за сутки — 4 500 бат",
     80000.0, "month", "уточнение в скобках между меткой и ценой"),
    ("Сутки от 800 бат Неделя от 5 500 бат Месяц от 20 000 бат",
     20000.0, "month", "«от» перед каждой ценой"),
    ("Свеженький дом! Месяц- 38 тыс бат Электричество 7 бат за юнит Сутки 1400",
     38000.0, "month", "тысячи словом"),
    ("Минимальный срок аренды 3 мес. \n\n25 000 при оплате за 3 мес сразу. Депозит 10000 бат",
     25000.0, "month", "цена на следующей строке после метки, депозит не мешает"),
    ("Дом 2 спальни, 35000 в месяц", 35000.0, "month", "простая форма"),
    ("Bungalow 1500 baht per night, minimum 3 nights", 1500.0, "night", "англ. посуточно"),
    ("House for rent 30000 THB monthly", 30000.0, "month", "monthly после суммы"),
    ("Rent 22,000 baht/month", 22000.0, "month", "запятая как разделитель тысяч"),
    ("Villa 45k per month", 45000.0, "month", "k-нотация"),
    ("Ночь - 1200 бат", 1200.0, "night", "метка перед ценой, посуточно"),
    ("Дом в Шритану, 28 000 бат", 28000.0, "month", "период достраивается по величине"),
    ("Апартаменты, свободные даты 13-15.02 / 2 дня за 3000 бат. Сутки 1500-1700 бат",
     1500.0, "night", "цена за N дней не выдаётся за суточную"),
    ("Haad yao Available from 18 march 25000 per month 6000 security deposit",
     25000.0, "month", "депозит справа от «per month» не подменяет цену"),
]

# Кейсы с «чужими» ценами в хвосте: владелец перечисляет другие свои объекты
# или технику. Цена основного объекта стоит выше, и брать надо её.
TAIL_CASES = [
    ("Семейная Вилла с бассейном доступна сейчас по цене 45 000thb, и на высокий сезон "
     "60 000thb. Вилла 65 кв.м, район Баан Суан, электричество по счётчику.\n\n"
     "✅ Также доступны другие премиум виллы 60-100кв.м с бассейнами по цене от 30 000бат/мес",
     45000.0, "month", "«также доступны» — цены других вилл в хвосте"),
    ("Пристраиваю свой домик на бантае. 1 спальня большая, большой зал, огромная терраса. "
     "Цена от хозяина 13.000 плюс ку. Дом полностью обустроен.\n"
     "Так же есть байк pcx 150. Вместе с домом отдам за 2000 бат в мес.",
     13000.0, "month", "цена байка в хвосте не должна перебивать цену дома"),
]


def main() -> None:
    failed = 0
    for text, price, period, why in CASES + TAIL_CASES:
        got = _parse_price(text)
        ok = got == (price, period)
        failed += not ok
        mark = "✓" if ok else "✗"
        print(f"  {mark} {str(got):22} {why}")
        if not ok:
            print(f"      ожидалось ({price}, {period!r})")
            print(f"      текст: {' '.join(text.split())[:110]}")

    total = len(CASES) + len(TAIL_CASES)
    if failed:
        print(f"\n✗ цены: провалено {failed} из {total}")
        sys.exit(1)
    print(f"\n✓ цены: все {total} проверок пройдены")


if __name__ == "__main__":
    main()
